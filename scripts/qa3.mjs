import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--disable-webgl','--disable-webgl2'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
const p = await ctx.newPage();
p.on('pageerror', e => console.log('[pageerror]', e.message));
await p.goto('http://127.0.0.1:5180/', { waitUntil: 'load' });
await p.waitForTimeout(1500);
console.log('body:', await p.evaluate(() => document.body.className));
console.log('items:', await p.evaluate(() => document.querySelectorAll('.fallback__item').length));
console.log('gallery:', await p.evaluate(() => !!window.__exhibition.gallery));
await p.screenshot({ path: 'shots/qa-fallback.png' });
await p.setViewportSize({ width: 390, height: 844 });
await p.waitForTimeout(400);
await p.screenshot({ path: 'shots/qa-fallback-mobile.png' });
await b.close();
