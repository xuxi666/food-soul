import { chromium } from 'playwright-core';
const BASE='http://127.0.0.1:5180';
const b = await chromium.launch({ executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true, args:['--enable-gpu','--use-angle=d3d11','--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport:{width:390,height:844}, deviceScaleFactor:2, isMobile:true, hasTouch:true });
const p = await ctx.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(e.message));
await p.goto(BASE+'/',{waitUntil:'load'});
await p.waitForTimeout(3200);
await p.screenshot({path:'shots/v2-m-home.png'});
await p.evaluate(()=>document.querySelector('#board').scrollIntoView());
await p.waitForTimeout(800);
await p.screenshot({path:'shots/v2-m-board.png'});
await p.evaluate(()=>document.querySelector('#personas').scrollIntoView());
await p.waitForTimeout(1500);
await p.screenshot({path:'shots/v2-m-personas.png'});
await p.goto(BASE+'/chat/mapo-tofu',{waitUntil:'load'});
await p.waitForTimeout(1500);
await p.screenshot({path:'shots/v2-m-chat.png'});
await p.goto(BASE+'/recipe?dish=mapo-tofu',{waitUntil:'load'});
await p.waitForTimeout(2200);
await p.screenshot({path:'shots/v2-m-recipe.png'});
console.log('scroll width check:', await p.evaluate(()=>`${document.documentElement.scrollWidth} / ${innerWidth}`));
console.log('errors:', errs.length?errs:'none');
await b.close();
